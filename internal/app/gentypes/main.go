// Command gentypes emits the TypeScript API types from internal/app/types.go.
//
// It intentionally parses the source instead of reflecting, so named string
// types can become literal unions from their const block and the output keeps
// the declaration order. Run it with `go generate ./internal/app`.
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
)

func main() {
	root, err := findRoot()
	if err != nil {
		fail(err)
	}
	src := filepath.Join(root, "internal", "app", "types.go")
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, src, nil, parser.ParseComments)
	if err != nil {
		fail(err)
	}

	consts := collectStringConsts(file)

	var out strings.Builder
	out.WriteString("// Code generated by go generate ./internal/app; DO NOT EDIT.\n")
	out.WriteString("// Source: internal/app/types.go\n\n")

	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			switch t := ts.Type.(type) {
			case *ast.StructType:
				emitStruct(&out, ts.Name.Name, t)
			case *ast.Ident:
				if t.Name == "string" {
					emitStringType(&out, ts.Name.Name, consts[ts.Name.Name])
				}
			}
		}
	}

	dst := filepath.Join(root, "web", "src", "types.ts")
	if err := os.WriteFile(dst, []byte(out.String()), 0o644); err != nil {
		fail(err)
	}
}

func emitStringType(out *strings.Builder, name string, values []string) {
	if len(values) == 0 {
		fmt.Fprintf(out, "export type %s = string\n\n", name)
		return
	}
	quoted := make([]string, 0, len(values))
	for _, v := range values {
		quoted = append(quoted, strconv.Quote(v))
	}
	fmt.Fprintf(out, "export type %s = %s\n\n", name, strings.Join(quoted, " | "))
}

func emitStruct(out *strings.Builder, name string, st *ast.StructType) {
	var embedded []string
	type field struct {
		name     string
		typ      string
		optional bool
	}
	var fields []field
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			embedded = append(embedded, tsType(f.Type))
			continue
		}
		tag := ""
		if f.Tag != nil {
			tag = reflect.StructTag(strings.Trim(f.Tag.Value, "`")).Get("json")
		}
		parts := strings.Split(tag, ",")
		jsonName := parts[0]
		if jsonName == "-" {
			continue
		}
		if jsonName == "" {
			jsonName = f.Names[0].Name
		}
		optional := false
		for _, p := range parts[1:] {
			if p == "omitempty" {
				optional = true
			}
		}
		if _, ok := f.Type.(*ast.StarExpr); ok {
			optional = true
		}
		for _, n := range f.Names {
			if !ast.IsExported(n.Name) {
				continue
			}
			fields = append(fields, field{name: jsonName, typ: tsType(f.Type), optional: optional})
		}
	}

	if len(embedded) > 0 {
		fmt.Fprintf(out, "export interface %s extends %s {\n", name, strings.Join(embedded, ", "))
	} else {
		fmt.Fprintf(out, "export interface %s {\n", name)
	}
	for _, f := range fields {
		q := ""
		if f.optional {
			q = "?"
		}
		fmt.Fprintf(out, "  %s%s: %s\n", f.name, q, f.typ)
	}
	out.WriteString("}\n\n")
}

func tsType(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "string"
		case "int", "int64", "int32", "uint", "uint64", "float64", "float32":
			return "number"
		case "bool":
			return "boolean"
		case "any":
			return "unknown"
		default:
			return t.Name
		}
	case *ast.StarExpr:
		return tsType(t.X)
	case *ast.ArrayType:
		return tsType(t.Elt) + "[]"
	case *ast.MapType:
		return "Record<string, " + tsType(t.Value) + ">"
	case *ast.SelectorExpr:
		return t.Sel.Name
	default:
		return "unknown"
	}
}

func collectStringConsts(file *ast.File) map[string][]string {
	out := map[string][]string{}
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		for _, spec := range gd.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			ident, ok := vs.Type.(*ast.Ident)
			if !ok {
				continue
			}
			for _, value := range vs.Values {
				lit, ok := value.(*ast.BasicLit)
				if !ok || lit.Kind != token.STRING {
					continue
				}
				s, err := strconv.Unquote(lit.Value)
				if err != nil {
					continue
				}
				out[ident.Name] = append(out[ident.Name], s)
			}
		}
	}
	return out
}

func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found above %s", dir)
		}
		dir = parent
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
